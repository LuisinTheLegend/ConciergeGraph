/**
 * Graph Topology Types
 *
 * TypeScript types for the Grafo Concierge topology,
 * mapped from the SQLite tables (nodes/edges) of the Python backend.
 */

// ─── Node Types (provenance) ──────────────────────────────────────────────

export type GrafoNodeType =
  | "CLASS"
  | "FACT"
  | "FUNCTION"
  | "METHOD"
  | "MODULE"
  | "INSIGHT"
  | string; // fallback for future types

// ─── Color Palette by Node Type ─────────────────────────────────────────────

export const NODE_TYPE_COLORS: Record<string, string> = {
  CLASS: "#93c5fd",     // Pastel Blue
  MODULE: "#a5f3fc",    // Pastel Cyan
  FUNCTION: "#a7f3d0",  // Pastel Emerald
  METHOD: "#c084fc",    // Pastel Lilac
  FACT: "#fdba74",      // Soft Peach/Orange
  INSIGHT: "#fbcfe8",   // Pastel Pink
  DEFAULT: "#9ca3af",   // Soft Slate/Gray
};

export function getNodeColor(nodeType: string): string {
  return NODE_TYPE_COLORS[nodeType] ?? NODE_TYPE_COLORS.DEFAULT;
}

// ─── Graph Node (from concierge_search response) ────────────────────────────

export interface GrafoNode {
  /** Unique node ID in SQLite */
  id: number;
  /** Node label/name (e.g. "storage/store.py::SqliteStore") */
  label: string;
  /** Descriptive summary generated by the pipeline */
  summary: string | null;
  /** Provenance type */
  node_type: GrafoNodeType;
  /** Associated tags */
  tags: string[] | null;
  /** Relevance score (if returned from search) */
  hybrid_score?: number;
  /** Is it a super node (community)? */
  is_super_node?: boolean;
}

// ─── Graph Edge (from edges table) ──────────────────────────────────────────

export interface GrafoEdge {
  /** Source node ID */
  source: number;
  /** Target node ID */
  target: number;
  /** Relationship type */
  relation_type?: string;
}

// ─── Force Graph Data Format ────────────────────────────────────────────────
// Format expected by react-force-graph-3d

export interface ForceGraphNode extends GrafoNode {
  /** Calculated color based on node_type */
  color: string;
  /** Visual size of the node (based on degree/importance) */
  val: number;
  // Positions calculated by the force simulation
  x?: number;
  y?: number;
  z?: number;
  fx?: number;
  fy?: number;
  fz?: number;
}

export interface ForceGraphLink {
  source: number | ForceGraphNode;
  target: number | ForceGraphNode;
  relation_type?: string;
}

export interface ForceGraphData {
  nodes: ForceGraphNode[];
  links: ForceGraphLink[];
}

// ─── MCP Search Response (partial, for typing) ────────────────────────────

export interface McpSearchResult {
  node_id: number;
  label: string;
  summary: string | null;
  node_type: GrafoNodeType;
  tags: string[] | null;
  hybrid_score: number;
  is_super_node: boolean;
}

export interface McpSearchResponse {
  success: boolean;
  results: McpSearchResult[];
  results_count: number;
}

// ─── MCP Load Response (partial, for edges) ─────────────────────────────

export interface McpLoadEdge {
  source_id: number;
  target_id: number;
  relation_type: string;
}

export interface McpLoadResponse {
  success: boolean;
  node: {
    id: number;
    label: string;
    node_type: string;
    summary: string | null;
    tags: string[] | null;
  };
  edges_from: McpLoadEdge[];
  edges_to: McpLoadEdge[];
}

// ─── MCP Status Response (partial, for stats) ─────────────────────────────

export interface McpStatusResponse {
  success: boolean;
  project?: {
    project: {
      uuid: string;
      folder_name: string;
    };
    stats: {
      nodes: number;
      nodes_by_type: Record<string, number>;
      edges: number;
    };
  };
}
